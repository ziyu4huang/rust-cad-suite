//! `write_rtlil -readable` 打印機:逐形照抄 oracle `RTLIL_BACKEND` 家族
//! (vendor-reference/yosys backends/rtlil/rtlil_backend.cc:35-404)。
//!
//! -readable 形=clone v0.70 的傳統全名 dump(binary 0.70+179 的默認形已改
//! twines 壓縮,RYOSYS-MVP §0-6;兩源分歧以 binary 實錄 golden 為準)。
//!
//! 迭代語義:屬性/參數/連線/模組按插入序傾印(oracle dict reversed);
//! chunk 重建規則=kernel/rtlil.h `next_chunk_bits`(值序連續+物理 offset
//! 遞增的 wire 位合併、相鄰常數位合併)。

use crate::ast::*;
use std::collections::HashMap;

/// 輸出首行自標識(歸一化契約剝除;D-ys1:不冒充 oracle 版本串)。
const GENERATED_BY: &str = concat!("# Generated by ryosys ", env!("CARGO_PKG_VERSION"));

/// 整個 design 的 `-readable` 傾印。
pub fn write_readable(design: &Design) -> String {
    let mut out = String::new();
    out.push_str(GENERATED_BY);
    out.push('\n');
    dump_design(&mut out, design);
    out
}

fn dump_design(out: &mut String, design: &Design) {
    out.push_str(&format!("autoidx {}\n", design.autoidx));
    for module in &design.modules {
        dump_module(out, module);
    }
}

fn dump_module(out: &mut String, module: &Module) {
    dump_attributes(out, "", &module.attributes);
    out.push_str(&format!("module {}\n", module.name));

    if !module.avail_parameters.is_empty() {
        for p in &module.avail_parameters {
            match module.parameter_defaults.get(p) {
                None => out.push_str(&format!("  parameter {p}\n")),
                Some(c) => {
                    out.push_str(&format!("  parameter {p} "));
                    dump_const_whole(out, c);
                    out.push('\n');
                }
            }
        }
    }

    // wire 寬度表(dump_sigchunk 的裸名判斷需要宣告寬)。
    let mut wire_widths: HashMap<&str, i64> = HashMap::new();
    for w in &module.wires {
        wire_widths.insert(w.name.as_str(), w.width);
    }

    for wire in &module.wires {
        dump_wire(out, "  ", wire);
    }
    for memory in &module.memories {
        dump_memory(out, "  ", memory);
    }
    for cell in &module.cells {
        dump_cell(out, "  ", cell, &wire_widths);
    }
    for process in &module.processes {
        dump_proc(out, "  ", process, &wire_widths);
    }
    for (lhs, rhs) in &module.connections {
        dump_conn(out, "  ", lhs, rhs, &wire_widths);
    }
    out.push_str("end\n");
}

fn dump_attributes(out: &mut String, indent: &str, attrs: &InsertMap<Const>) {
    for (name, value) in &attrs.entries {
        out.push_str(&format!("{indent}attribute {name} "));
        dump_const_whole(out, value);
        out.push('\n');
    }
}

/// dump_const 的整數實體(屬性/參數):autoint=true(rtlil_backend.cc:44-104)。
fn dump_const_whole(out: &mut String, c: &Const) {
    match c {
        Const::Str(s) => dump_string(out, s),
        Const::Bits { width, bits, signed, is_unsized } => {
            dump_const_bits(out, bits, *width, true, *signed, *is_unsized);
        }
    }
}

/// dump_const 的位域核心。autoint:width==32 且全定值且 val>=0 時印十進制
/// (同值異形:40'1010 補零後非 32 不 autoint;-3 整數是 32-bit 二補數,
/// 最高位 1 → val<0 → 回退二進制形)。
fn dump_const_bits(
    out: &mut String,
    bits: &[Bit],
    width: i64,
    autoint: bool,
    signed: bool,
    is_unsized: bool,
) {
    if width == 32 && autoint {
        let mut val: u32 = 0;
        let mut fully_defined = true;
        for (i, &b) in bits.iter().enumerate().take(32) {
            match b {
                Bit::S0 => {}
                Bit::S1 => val |= 1 << i,
                _ => fully_defined = false,
            }
        }
        if fully_defined && (val as i32) >= 0 {
            out.push_str(&format!("{val}"));
            return;
        }
    }
    if !is_unsized {
        out.push_str(&format!("{width}'"));
    }
    if signed {
        out.push('s');
    }
    // is_fully_undef_x_only:空=真(0'x 形)。
    if bits.iter().all(|&b| b == Bit::Sx) {
        out.push('x');
    } else {
        for &b in bits.iter().rev() {
            out.push(b.as_char());
        }
    }
}

/// 字串轉義(rtlil_backend.cc:86-102):\n \t <32→\NNN(octal) " \\。
fn dump_string(out: &mut String, s: &str) {
    out.push('"');
    for ch in s.chars() {
        match ch {
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c if (c as u32) < 32 => out.push_str(&format!("\\{:03o}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
}

/// chunk 重建視圖(kernel/rtlil.h `Chunks::const_iterator::next_chunk_bits`):
/// 值序上連續且物理 offset 遞增連續的 wire 位合併;相鄰常數位合併。
pub enum ChunkView {
    Wire { wire: String, offset: i64, width: i64 },
    Const { start: usize, len: usize },
}

pub fn sig_chunks(sig: &SigSpec) -> Vec<ChunkView> {
    let mut out = Vec::new();
    let bits = &sig.bits;
    let mut i = 0;
    while i < bits.len() {
        match &bits[i] {
            SigBit::Wire { wire, offset } => {
                let (w, o) = (wire.clone(), *offset);
                let start = i;
                i += 1;
                while i < bits.len() {
                    if let SigBit::Wire { wire: w2, offset: o2 } = &bits[i] {
                        if w2 == &w && *o2 == o + (i as i64 - start as i64) {
                            i += 1;
                            continue;
                        }
                    }
                    break;
                }
                out.push(ChunkView::Wire { wire: w, offset: o, width: (i - start) as i64 });
            }
            SigBit::Const(_) => {
                let start = i;
                i += 1;
                while i < bits.len() {
                    if matches!(bits[i], SigBit::Const(_)) {
                        i += 1;
                    } else {
                        break;
                    }
                }
                out.push(ChunkView::Const { start, len: i - start });
            }
        }
    }
    out
}

/// dump_sigspec(rtlil_backend.cc:120-133):單 chunk 印本体(autoint=true),
/// 多 chunk 印 `{ c_n … c_1 }`(值序高位在前,chunk 內 autoint=false)。
fn dump_sigspec(out: &mut String, sig: &SigSpec, wire_widths: &HashMap<&str, i64>) {
    let chunks = sig_chunks(sig);
    if chunks.len() == 1 {
        dump_sigchunk(out, &chunks[0], sig, wire_widths, true);
    } else {
        out.push_str("{ ");
        for chunk in chunks.iter().rev() {
            dump_sigchunk(out, chunk, sig, wire_widths, false);
            out.push(' ');
        }
        out.push('}');
    }
}

fn dump_sigchunk(
    out: &mut String,
    chunk: &ChunkView,
    sig: &SigSpec,
    wire_widths: &HashMap<&str, i64>,
    autoint: bool,
) {
    match chunk {
        ChunkView::Wire { wire, offset, width } => {
            let decl_width = wire_widths.get(wire.as_str()).copied().unwrap_or(*width);
            if *width == decl_width && *offset == 0 {
                out.push_str(wire);
            } else if *width == 1 {
                out.push_str(&format!("{wire} [{offset}]"));
            } else {
                out.push_str(&format!("{wire} [{}:{}]", offset + width - 1, offset));
            }
        }
        ChunkView::Const { start, len } => {
            // chunk 內必全為常數位(構建保證);chunk 常數無 signed/unsized
            // flags(SigSpec 域即丟,R7)。
            let bits: Vec<Bit> = sig.bits[*start..*start + *len]
                .iter()
                .filter_map(|b| match b {
                    SigBit::Const(x) => Some(*x),
                    _ => None,
                })
                .collect();
            dump_const_bits(out, &bits, *len as i64, autoint, false, false);
        }
    }
}

fn dump_wire(out: &mut String, indent: &str, wire: &Wire) {
    dump_attributes(out, indent, &wire.attributes);
    out.push_str(&format!("{indent}wire "));
    if wire.width != 1 {
        out.push_str(&format!("width {} ", wire.width));
    }
    if wire.upto {
        out.push_str("upto ");
    }
    if wire.start_offset != 0 {
        out.push_str(&format!("offset {} ", wire.start_offset));
    }
    if wire.port_input && !wire.port_output {
        out.push_str(&format!("input {} ", wire.port_id));
    }
    if !wire.port_input && wire.port_output {
        out.push_str(&format!("output {} ", wire.port_id));
    }
    if wire.port_input && wire.port_output {
        out.push_str(&format!("inout {} ", wire.port_id));
    }
    if wire.is_signed {
        out.push_str("signed ");
    }
    out.push_str(&wire.name);
    out.push('\n');
}

fn dump_memory(out: &mut String, indent: &str, memory: &Memory) {
    dump_attributes(out, indent, &memory.attributes);
    out.push_str(&format!("{indent}memory "));
    if memory.width != 1 {
        out.push_str(&format!("width {} ", memory.width));
    }
    if memory.size != 0 {
        out.push_str(&format!("size {} ", memory.size));
    }
    if memory.start_offset != 0 {
        out.push_str(&format!("offset {} ", memory.start_offset));
    }
    out.push_str(&memory.name);
    out.push('\n');
}

fn dump_cell(out: &mut String, indent: &str, cell: &Cell, wire_widths: &HashMap<&str, i64>) {
    dump_attributes(out, indent, &cell.attributes);
    out.push_str(&format!("{indent}cell {} {}\n", cell.ctype, cell.name));
    for (name, param) in &cell.parameters.entries {
        let (signed, is_unsized) = match param {
            Const::Bits { signed, is_unsized, .. } => (*signed, *is_unsized),
            Const::Str(_) => (false, false),
        };
        let mut flags = String::new();
        if signed {
            flags.push_str(" signed");
        }
        if is_unsized {
            flags.push_str(" unsized");
        }
        out.push_str(&format!("{indent}  parameter{flags} {name} "));
        dump_const_whole(out, param);
        out.push('\n');
    }
    for (port, sig) in &cell.connections {
        out.push_str(&format!("{indent}  connect {port} "));
        dump_sigspec(out, sig, wire_widths);
        out.push('\n');
    }
    out.push_str(&format!("{indent}end\n"));
}

fn dump_proc(out: &mut String, indent: &str, proc: &Process, wire_widths: &HashMap<&str, i64>) {
    dump_attributes(out, indent, &proc.attributes);
    out.push_str(&format!("{indent}process {}\n", proc.name));
    dump_proc_case_body(out, &format!("{indent}  "), &proc.root_case, wire_widths);
    for sync in &proc.syncs {
        dump_proc_sync(out, &format!("{indent}  "), sync, wire_widths);
    }
    out.push_str(&format!("{indent}end\n"));
}

fn dump_proc_case_body(
    out: &mut String,
    indent: &str,
    cs: &CaseRule,
    wire_widths: &HashMap<&str, i64>,
) {
    for (lhs, rhs) in &cs.actions {
        out.push_str(&format!("{indent}assign "));
        dump_sigspec(out, lhs, wire_widths);
        out.push(' ');
        dump_sigspec(out, rhs, wire_widths);
        out.push('\n');
    }
    for sw in &cs.switches {
        dump_proc_switch(out, indent, sw, wire_widths);
    }
}

fn dump_proc_switch(
    out: &mut String,
    indent: &str,
    sw: &SwitchRule,
    wire_widths: &HashMap<&str, i64>,
) {
    dump_attributes(out, indent, &sw.attributes);
    out.push_str(&format!("{indent}switch "));
    dump_sigspec(out, &sw.signal, wire_widths);
    out.push('\n');

    for case in &sw.cases {
        dump_attributes(out, indent, &case.attributes);
        // 空 compare 印 `case `(尾隨空格)——oracle 逐字。
        out.push_str(&format!("{indent}  case "));
        for (i, cmp) in case.compare.iter().enumerate() {
            if i > 0 {
                out.push_str(" , ");
            }
            dump_sigspec(out, cmp, wire_widths);
        }
        out.push('\n');
        dump_proc_case_body(out, &format!("{indent}    "), case, wire_widths);
    }
    out.push_str(&format!("{indent}end\n"));
}

fn dump_proc_sync(
    out: &mut String,
    indent: &str,
    sy: &SyncRule,
    wire_widths: &HashMap<&str, i64>,
) {
    out.push_str(&format!("{indent}sync "));
    match sy.stype {
        SyncType::Low => {
            out.push_str("low ");
            dump_sigspec(out, sy.signal.as_ref().unwrap(), wire_widths);
            out.push('\n');
        }
        SyncType::High => {
            out.push_str("high ");
            dump_sigspec(out, sy.signal.as_ref().unwrap(), wire_widths);
            out.push('\n');
        }
        SyncType::Posedge => {
            out.push_str("posedge ");
            dump_sigspec(out, sy.signal.as_ref().unwrap(), wire_widths);
            out.push('\n');
        }
        SyncType::Negedge => {
            out.push_str("negedge ");
            dump_sigspec(out, sy.signal.as_ref().unwrap(), wire_widths);
            out.push('\n');
        }
        SyncType::Edge => {
            out.push_str("edge ");
            dump_sigspec(out, sy.signal.as_ref().unwrap(), wire_widths);
            out.push('\n');
        }
        SyncType::Always => out.push_str("always\n"),
        SyncType::Global => out.push_str("global\n"),
        SyncType::Init => out.push_str("init\n"),
    }

    for (lhs, rhs) in &sy.actions {
        out.push_str(&format!("{indent}  update "));
        dump_sigspec(out, lhs, wire_widths);
        out.push(' ');
        dump_sigspec(out, rhs, wire_widths);
        out.push('\n');
    }

    for mwa in &sy.mem_writes {
        dump_attributes(out, indent, &mwa.attributes);
        out.push_str(&format!("{indent}  memwr {} ", mwa.memid));
        dump_sigspec(out, &mwa.address, wire_widths);
        out.push(' ');
        dump_sigspec(out, &mwa.data, wire_widths);
        out.push(' ');
        dump_sigspec(out, &mwa.enable, wire_widths);
        out.push(' ');
        dump_const_whole(out, &mwa.priority_mask);
        out.push('\n');
    }
}

fn dump_conn(
    out: &mut String,
    indent: &str,
    lhs: &SigSpec,
    rhs: &SigSpec,
    wire_widths: &HashMap<&str, i64>,
) {
    out.push_str(&format!("{indent}connect "));
    dump_sigspec(out, lhs, wire_widths);
    out.push(' ');
    dump_sigspec(out, rhs, wire_widths);
    out.push('\n');
}
