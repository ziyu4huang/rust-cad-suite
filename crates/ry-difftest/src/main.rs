//! ry-difftest — ryosys 的 oracle 差分 harness(RYOSYS-MVP §4)。
//!
//! 兩個面:
//!   ry-difftest --record [--corpus corpus/ys-e2e]
//!     錄製輪(oracle 在場):全量兩層語料。階段 A(oracle 獨有預處理,
//!     stdout/stderr 全棄)+ 階段 B(統一脚本,RYOSYS-MVP §4.1 逐字):
//!       `read_rtlil case.il; check; stat; write_rtlil -readable
//!        expected.rtlil; write_json expected.json`
//!     產出五件套 case.il/expected.rtlil/expected.json/expected.stdout/
//!     expected.stderr/expected.exit 入 git;P-bearing 例 write_json 硬錯
//!     → exit=1+expected.stderr 逐字+不錄 expected.json(oracle 只產
//!     0-byte 空檔,錄製輪刪除)。
//!   ry-difftest --corpus corpus/ys-e2e
//!     常態(零 oracle):每案例複製 case.il 到 pid-unique 臨時目錄,以
//!     **同一條** -p script 驅動 ryosys,同歸一化,對 committed expected.*
//!     逐 byte 比對 + exit code 相等。產物存在≠成功(R4)。
//!
//! 輸出:每案例一行 `<case>\t<status>\t<detail>`,末行
//! `SUMMARY ys=<p>/<n>`;exit 0 恒定——執法在 scripts/regress.sh 的
//! 精確數 grep(基線=402/402,M1 弧末:M0 層全量+87 -hier+87 -rj+
//! 87 -sm[simplemap 層])。
//!
//! 歸一化契約(RYOSYS-MVP §4.2,敵意 fixture 由 tests/normalize.rs 釘死):
//! * stdout:prologue 切(首個 `-- Running command ` 行前全丟,該行保留)
//!   + epilogue 切(首個 `End of script. Logfile hash:` 行起到 EOF);
//!   中段(含 check Warning、stat 表)byte-exact,歸一化禁內容改寫。
//! * .il:剝首行(前綴 `# Generated by `)。
//! * .json:剝 `"creator": ` 行。
//! * stderr:零歸一化,逐字對拍。

use ry_difftest::{normalize_il, normalize_json, normalize_stdout, SCRIPT_B};

/// M1 擴容層(RYOSYS-MVP §3-M1 閘①):-hier=hierarchy 縱切;-rj=
/// read_json 自家輸出閉環(輸入 a.json 由 oracle 從 case.il 預產);
/// -sm=simplemap 映射層(M1-d,§7.1-3 腳本逐字)。
const SCRIPT_HIER: &str = "read_rtlil case.il; hierarchy -auto-top; check; stat; write_rtlil -readable expected.rtlil; write_json expected.json";
const SCRIPT_RJ: &str = "read_json a.json; check; stat; write_rtlil -readable expected.rtlil; write_json expected.json";
const SCRIPT_SM: &str = "read_rtlil case.il; simplemap; check; stat; write_rtlil -readable expected.rtlil; write_json expected.json";
/// M2 翻轉腳本(§8.2-P2 逐字;-pb 層):-pb 層錄製與 compare 同一常量
/// (RM2-7:結構上不可能單側翻)。
pub const SCRIPT_PB: &str = "read_rtlil case.il; proc; check; stat; write_rtlil -readable expected.rtlil; write_json expected.json";
/// M3 擴容層(RYOSYS-MVP §9.1-5 逐字;-pbo 層):-pb 輸入 + opt 全鏈。
pub const SCRIPT_PBO: &str = "read_rtlil case.il; proc; opt; check; stat; write_rtlil -readable expected.rtlil; write_json expected.json";
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

fn repo_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn oracle_path() -> PathBuf {
    repo_root().join("vendor-reference/suite-dl/oss-cad-suite/bin/yosys")
}

fn ryosys_path() -> PathBuf {
    // 對拍取 target/debug/ryosys(regress 先 cargo build 再跑本 harness)。
    repo_root().join("target/debug/ryosys")
}

// ---------------------------------------------------------------------------
// 錄製輪(--record;oracle 在場)
// ---------------------------------------------------------------------------

fn run_in(dir: &Path, yosys: &Path, script: &str) -> (i32, String, String) {
    let out = Command::new(yosys)
        .arg("-p")
        .arg(script)
        .current_dir(dir)
        .output()
        .expect("spawn oracle");
    (
        out.status.code().unwrap_or(-1),
        String::from_utf8_lossy(&out.stdout).into_owned(),
        String::from_utf8_lossy(&out.stderr).into_owned(),
    )
}

fn record(corpus: &Path) {
    let yosys = oracle_path();
    assert!(yosys.exists(), "oracle 不在場:{}", yosys.display());
    let src_dir = repo_root().join("corpus-external/yosys-simple");
    let mut files: Vec<String> = fs::read_dir(&src_dir)
        .expect("corpus-external/yosys-simple")
        .flatten()
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .filter(|n| n.ends_with(".v"))
        .collect();
    files.sort();

    let mut excluded: Vec<String> = Vec::new();
    let mut n_pfree = 0usize;
    let mut n_pbearing = 0usize;
    let mut n_pbo = 0usize;

    for f in &files {
        let stem = f.trim_end_matches(".v").to_string();
        let rel = format!("../../../corpus-external/yosys-simple/{f}");
        // 兩層各錄階段 A(§4.1 逐字;stdout/stderr 全棄)。
        for (suffix, with_proc) in [("", true), ("-pb", false)] {
            let dir = corpus.join(format!("{stem}{suffix}"));
            fs::create_dir_all(&dir).unwrap();
            let script = if with_proc {
                format!("read_verilog {rel}; hierarchy -auto-top; proc; opt; write_rtlil -readable case.il")
            } else {
                format!("read_verilog {rel}; hierarchy -auto-top; write_rtlil -readable case.il")
            };
            let (rc, _so, _se) = run_in(&dir, &yosys, &script);
            if rc != 0 {
                excluded.push(format!("{stem}{suffix}: stage A exit={rc}"));
                let _ = fs::remove_dir_all(&dir);
                continue;
            }
            // P-bearing 層只收含 process 區塊的案例(§0-13:54/87)。
            let il = fs::read_to_string(dir.join("case.il")).unwrap_or_default();
            if !with_proc && !il.contains("\n  process ") {
                let _ = fs::remove_dir_all(&dir);
                continue;
            }
            // 階段 B:P-free 層=統一脚本(§4.1);-pb 層=翻轉腳本
            // (SCRIPT_PB,§8.3-7——M2 翻轉後 -pb 層 exit=0+expected.json)。
            let script_b = if with_proc { SCRIPT_B } else { SCRIPT_PB };
            let (rc, so, se) = run_in(&dir, &yosys, script_b);
            fs::write(dir.join("expected.stdout"), normalize_stdout(&so)).unwrap();
            fs::write(dir.join("expected.stderr"), se).unwrap();
            fs::write(dir.join("expected.exit"), format!("{rc}\n")).unwrap();
            if rc != 0 {
                // oracle 的 write_json 硬錯只留下 0-byte 空檔(緩衝未落盤),
                // golden 不錄該檔(§4.1)。
                let _ = fs::remove_file(dir.join("expected.json"));
            }
            // with_proc=true=P-free 層(階段 A 含 proc;opt);M1 層只對
            // P-free 錄(write_json 須成功)。
            if with_proc {
                n_pfree += 1;
                // M1 層:-hier(同 case.il)+ -rj(先產 a.json)+ -sm(M1-d)。
                let hdir = corpus.join(format!("{stem}-hier"));
                fs::create_dir_all(&hdir).unwrap();
                fs::copy(dir.join("case.il"), hdir.join("case.il")).unwrap();
                fs::write(hdir.join("script.txt"), format!("{SCRIPT_HIER}\n")).unwrap();
                let (rc, so, se) = run_in(&hdir, &yosys, SCRIPT_HIER);
                write_golden(&hdir, rc, &so, &se);

                let rdir = corpus.join(format!("{stem}-rj"));
                fs::create_dir_all(&rdir).unwrap();
                fs::copy(dir.join("case.il"), rdir.join("case.il")).unwrap();
                fs::write(rdir.join("script.txt"), format!("{SCRIPT_RJ}\n")).unwrap();
                let (rc, _, _) = run_in(
                    &rdir,
                    &yosys,
                    "read_rtlil case.il; write_json a.json",
                );
                assert_eq!(rc, 0, "{stem}-rj 預產 a.json 失敗");
                let (rc, so, se) = run_in(&rdir, &yosys, SCRIPT_RJ);
                write_golden(&rdir, rc, &so, &se);

                let sdir = corpus.join(format!("{stem}-sm"));
                fs::create_dir_all(&sdir).unwrap();
                fs::copy(dir.join("case.il"), sdir.join("case.il")).unwrap();
                fs::write(sdir.join("script.txt"), format!("{SCRIPT_SM}\n")).unwrap();
                let (rc, so, se) = run_in(&sdir, &yosys, SCRIPT_SM);
                write_golden(&sdir, rc, &so, &se);
            } else {
                // -pb 層的腳本檔(與 -hier/-rj/-sm 同機制;M2 翻轉腳本)。
                fs::write(dir.join("script.txt"), format!("{SCRIPT_PB}\n")).unwrap();
                n_pbearing += 1;
                // M3 層:-pbo(同 case.il;opt 全鏈,§9.1-5 逐字)。
                let pdir = corpus.join(format!("{stem}-pbo"));
                fs::create_dir_all(&pdir).unwrap();
                fs::copy(dir.join("case.il"), pdir.join("case.il")).unwrap();
                fs::write(pdir.join("script.txt"), format!("{SCRIPT_PBO}\n")).unwrap();
                let (rc, so, se) = run_in(&pdir, &yosys, SCRIPT_PBO);
                write_golden(&pdir, rc, &so, &se);
                n_pbo += 1;
            }
        }
    }
    println!(
        "recorded pfree={n_pfree} pbearing={n_pbearing} pbo={n_pbo} total={}",
        n_pfree + n_pbearing + n_pbo
    );
    if !excluded.is_empty() {
        println!("EXCLUDED (登記入 PROVENANCE 排除表):");
        for e in &excluded {
            println!("  {e}");
        }
    }
}

