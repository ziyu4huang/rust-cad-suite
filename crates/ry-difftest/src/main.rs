/// 階段 B golden 落盤(統一歸一化;exit!=0 刪 expected.json)。
fn write_golden(dir: &Path, rc: i32, so: &str, se: &str) {
    fs::write(dir.join("expected.stdout"), normalize_stdout(so)).unwrap();
    fs::write(dir.join("expected.stderr"), se).unwrap();
    fs::write(dir.join("expected.exit"), format!("{rc}\n")).unwrap();
    if rc != 0 {
        let _ = fs::remove_file(dir.join("expected.json"));
    }
}

fn compare(corpus: &Path) {
    let ryosys = ryosys_path();
    assert!(ryosys.exists(), "ryosys 不在場(先 cargo build -p ry-cli):{}", ryosys.display());
    let mut cases: Vec<String> = fs::read_dir(corpus)
        .expect("corpus dir")
        .flatten()
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .filter(|n| fs::read_dir(corpus.join(n)).map(|d| d.count() > 0).unwrap_or(false))
        .collect();
    cases.sort();

    let work_root = std::env::temp_dir().join(format!("ry-difftest-{}", std::process::id()));
    let _ = fs::remove_dir_all(&work_root);
    fs::create_dir_all(&work_root).unwrap();

    let mut pass = 0usize;
    let mut lines: Vec<String> = Vec::new();
    for case in &cases {
        let dir = corpus.join(case);
        if !dir.join("case.il").exists() || !dir.join("expected.rtlil").exists() {
            continue; // 非案例目錄(PROVENANCE 等)
        }
        let work = work_root.join(case);
        fs::create_dir_all(&work).unwrap();
        for input in ["case.il", "a.json"] {
            if dir.join(input).exists() {
                fs::copy(dir.join(input), work.join(input)).unwrap();
            }
        }
        // 臨時目錄內不該帶 golden——腳本輸出名=expected.*,先清掉以防抄襲。
        let _ = fs::remove_file(work.join("expected.rtlil"));
        let _ = fs::remove_file(work.join("expected.json"));

        // per-case 腳本(M1 層);無 script.txt=SCRIPT_B(M0 層)。
        let script = fs::read_to_string(dir.join("script.txt"))
            .map(|t| t.trim_end_matches('\n').to_string())
            .unwrap_or_else(|_| SCRIPT_B.to_string());

        let out = Command::new(&ryosys)
            .arg("-p")
            .arg(&script)
            .current_dir(&work)
            .output()
            .expect("spawn ryosys");
        let rc = out.status.code().unwrap_or(-1);
        let so = String::from_utf8_lossy(&out.stdout).into_owned();
        let se = String::from_utf8_lossy(&out.stderr).into_owned();

        let exp_exit: i32 = fs::read_to_string(dir.join("expected.exit"))
            .unwrap()
            .trim()
            .parse()
            .unwrap();
        let exp_stdout = fs::read_to_string(dir.join("expected.stdout")).unwrap();
        let exp_stderr = fs::read_to_string(dir.join("expected.stderr")).unwrap();
        let exp_il = fs::read_to_string(dir.join("expected.rtlil")).unwrap();
        let exp_json = fs::read_to_string(dir.join("expected.json")).ok();

        let mut bad: Vec<&str> = Vec::new();
        if rc != exp_exit {
            bad.push("exit");
        }
        if se != exp_stderr {
            bad.push("stderr");
        }
        if normalize_stdout(&so) != exp_stdout {
            bad.push("stdout");
        }
        let got_il = fs::read_to_string(work.join("expected.rtlil")).unwrap_or_default();
        if normalize_il(&got_il) != normalize_il(&exp_il) {
            bad.push("rtlil");
        }
        match &exp_json {
            Some(golden) => {
                let got = fs::read_to_string(work.join("expected.json")).unwrap_or_default();
                if normalize_json(&got) != normalize_json(golden) {
                    bad.push("json");
                }
            }
            None => {
                // P-bearing:oracle 只產 0-byte 空檔;非空即紅。
                let got = fs::read_to_string(work.join("expected.json")).unwrap_or_default();
                if !got.is_empty() {
                    bad.push("json(nonempty)");
                }
            }
        }

        if bad.is_empty() {
            pass += 1;
            lines.push(format!("{case}\tPASS\t"));
        } else {
            lines.push(format!("{case}\tFAIL\t{}", bad.join(",")));
        }
    }
    let _ = fs::remove_dir_all(&work_root);
    for l in &lines {
        println!("{l}");
    }
    println!("SUMMARY ys={pass}/{}", lines.len());
}

/// live-compare 腿(RYOSYS-MVP §3-M1 閘③):oracle 在場時,全量重錄到
/// 臨時目錄並與入庫 golden 逐位元組對拍(歸一化同契約)——「oracle
/// 升級=語義漂移的即時探針」;缺 oracle=skip+note(exit 0,比照
/// lint-parity 閘形態)。
fn live_compare(corpus: &Path) {
    let yosys = oracle_path();
    if !yosys.exists() {
        println!("LIVE ys=skip (oracle absent: {})", yosys.display());
        return;
    }
    // 臨時 corpus 必須在 repo 樹內:階段 A 的相對路徑
    // `../../../corpus-external/…` 以案例目錄為 cwd(target/ 已 gitignore)。
    let temp = repo_root().join(format!("target/ry-live-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&temp);
    std::fs::create_dir_all(&temp).unwrap();
    record(&temp);
    let mut total = 0usize;
    let mut same = 0usize;
    let mut diffs: Vec<String> = Vec::new();
    for entry in std::fs::read_dir(corpus).unwrap().flatten() {
        let name = entry.file_name().to_string_lossy().into_owned();
        let gold_dir = corpus.join(&name);
        let live_dir = temp.join(&name);
        if !gold_dir.is_dir() || !live_dir.is_dir() || !gold_dir.join("expected.rtlil").exists() {
            continue;
        }
        total += 1;
        let mut ok = true;
        for f in ["expected.stdout", "expected.stderr", "expected.exit", "expected.rtlil"] {
            let (g, l) = if f == "expected.rtlil" {
                let g = normalize_il(&fs::read_to_string(gold_dir.join(f)).unwrap_or_default());
                let l = normalize_il(&fs::read_to_string(live_dir.join(f)).unwrap_or_default());
                (g.into_bytes(), l.into_bytes())
            } else {
                (
                    std::fs::read(gold_dir.join(f)).unwrap_or_default(),
                    std::fs::read(live_dir.join(f)).unwrap_or_default(),
                )
            };
            if g != l {
                ok = false;
                diffs.push(format!("{name}/{f}"));
            }
        }
        match (
            gold_dir.join("expected.json").exists(),
            live_dir.join("expected.json").exists(),
        ) {
            (true, true) => {
                let g = std::fs::read_to_string(gold_dir.join("expected.json")).unwrap();
                let l = std::fs::read_to_string(live_dir.join("expected.json")).unwrap();
                if normalize_json(&g) != normalize_json(&l) {
                    ok = false;
                    diffs.push(format!("{name}/expected.json"));
                }
            }
            (false, false) => {}
            _ => {
                ok = false;
                diffs.push(format!("{name}/expected.json presence"));
            }
        }
        if ok {
            same += 1;
        }
    }
    let _ = std::fs::remove_dir_all(&temp);
    println!("LIVE ys={same}/{total}");
    for d in diffs.iter().take(10) {
        println!("LIVE DIFF {d}");
    }
}

/// `--record-il <case-dir>`:對自寫 .il 案例(hand-authored fixture)用
/// oracle 錄階段 B golden——與 --record 同一條 SCRIPT_B/歸一化路徑
/// (單一歸一器紀律;鐵則:期望一律錄製,禁手寫)。
fn record_il(dir: &Path) {
    let yosys = oracle_path();
    assert!(yosys.exists(), "oracle 不在場:{}", yosys.display());
    let script = fs::read_to_string(dir.join("script.txt"))
        .map(|t| t.trim_end_matches('\n').to_string())
        .unwrap_or_else(|_| SCRIPT_B.to_string());
    let (rc, so, se) = run_in(dir, &yosys, &script);
    write_golden(dir, rc, &so, &se);
    println!("recorded {} exit={rc}", dir.display());
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let want_record = args.iter().any(|a| a == "--record");
    let want_live = args.iter().any(|a| a == "--live");
    let corpus = args
        .iter()
        .position(|a| a == "--corpus")
        .and_then(|i| args.get(i + 1))
        .map(PathBuf::from)
        .unwrap_or_else(|| repo_root().join("corpus/ys-e2e"));
    if want_record {
        record(&corpus);
    } else if let Some(i) = args.iter().position(|a| a == "--record-il") {
        record_il(&PathBuf::from(args.get(i + 1).expect("--record-il <dir>")));
    } else if want_live {
        live_compare(&corpus);
    } else {
        compare(&corpus);
    }
}
