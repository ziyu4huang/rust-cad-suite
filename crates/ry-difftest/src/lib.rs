//! ry-difftest 庫面:歸一化契約 + 階段 B 統一脚本常量(整合測試與
//! bin 共用;敵意 fixture 見 tests/normalize.rs)。

/// 階段 B 統一脚本(§4.1 逐字;錄製與對拍必須同一條——`-- Running
/// command` 橫幅逐字回顯該串,兩端一致才 byte-exact)。
pub const SCRIPT_B: &str = "read_rtlil case.il; check; stat; write_rtlil -readable expected.rtlil; write_json expected.json";

/// prologue/epilogue 結構切(RYOSYS-MVP §4.2)。
///
/// 行集合以 `\n` join、**無尾隨換行**為 golden 形態;「末尾換行分裂出
/// 的空元素」不是內容行——未觸 epilogue 即到 EOF 時(ryosys 的
/// log_error 中止徑)丟掉該空元素,否則會比 oracle 形多出一個尾 byte
/// (const_fold_func/always01-pb 對拍實錄 2026-10-27)。中段空行=
/// 內容,保留(敵意 fixture 釘死)。
pub fn normalize_stdout(text: &str) -> String {
    let mut out: Vec<&str> = Vec::new();
    let mut started = false;
    let mut broke = false;
    for line in text.split('\n') {
        if !started {
            if line.starts_with("-- Running command ") {
                started = true;
                out.push(line);
            }
            continue;
        }
        if line.starts_with("End of script. Logfile hash:") {
            broke = true;
            break;
        }
        out.push(line);
    }
    if !broke && out.last() == Some(&"") {
        out.pop();
    }
    out.join("\n")
}

/// 剝首行(前綴 `# Generated by `,D-ys1)。只剝第一行(敵意 fixture ③)。
/// 空 text(拒收形 golden 的 0-byte expected.rtlil,ys-m2-anchors)短路=空。
pub fn normalize_il(text: &str) -> String {
    if text.is_empty() {
        return String::new();
    }
    let mut it = text.splitn(2, '\n');
    let first = it.next().unwrap_or("");
    let rest = it.next().unwrap_or("");
    assert!(
        first.starts_with("# Generated by "),
        ".il 首行必為 Generated-by:{first:?}"
    );
    rest.to_string()
}

/// 剝 `"creator": ` 行(json.cc:294,D-ys1)。
pub fn normalize_json(text: &str) -> String {
    text.split('\n')
        .filter(|l| !l.contains("\"creator\": "))
        .collect::<Vec<_>>()
        .join("\n")
}
